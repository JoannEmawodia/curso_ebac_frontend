//função de multiplicação que deverá receber como argumentos dois números e retornar a multiplicação deles
function mutiplicacao(x:number, y:number):number{
    return x*y;
}

console.log(mutiplicacao(2,2));


//função de saudação que deverá receber um nome e retornar a concatenação “Olá “ + nome
function saudacao(nome: string):string{
return `Olá, ${nome}`;
}

console.log(saudacao("Marcia"));
